"""Build per-whole-art landmarks. Coordinates are in native original PNG pixels."""
from PIL import Image
from pathlib import Path
import json
root=Path(__file__).resolve().parents[1]
# Only visible eyes get eyelids; hair-covered eyes stay covered.
eyes={
'costume_apron':[(216,155,30,14,-5)],
'costume_bunny':[(212,271,28,15,-7)],
'costume_cardigan':[(184,133,29,14,-5)],
'costume_gown':[(217,136,29,15,-7)],
'costume_maid':[(212,127,31,15,-5)],
'costume_pool':[(191,129,29,15,-4)],
'costume_track':[(240,171,28,16,8),(305,184,27,15,8)],
'tier1':[(305,152,27,17,-12)],
'tier2':[(245,123,29,14,-3)],
'tier3':[(188,136,30,15,-8),(123,149,24,14,-8)],
'tier4':[(362,157,35,17,-15),(278,184,22,15,-15)],
'tier5':[(181,126,31,15,-8)],
}
result={}
for name,points in eyes.items():
 im=Image.open(root/f'assets/characters/{name}.png').convert('RGBA');w,h=im.size
 alpha=im.getchannel('A');bbox=alpha.getbbox();floor=bbox[3]-1
 # Pixel-derived contact cluster from the lowest solid 1% of the silhouette.
 xs=[]
 for x in range(w):
  if any(alpha.getpixel((x,y))>200 for y in range(max(0,floor-int(h*.008)),floor+1)): xs.append(x)
 groups=[]
 for x in xs:
  if not groups or x>groups[-1][-1]+2:groups.append([x])
  else:groups[-1].append(x)
 contacts=[{'x':(g[0]+g[-1])/2/w,'width':max(12,g[-1]-g[0])/w} for g in groups if len(g)>3]
 result[name]={'size':[w,h],'floor':floor/h,'contacts':contacts,'eyes':[]}
 for x,y,ew,eh,angle in points:
  # Skin below visible eye, avoiding the dark iris itself.
  samples=[]
  for sy in range(y+int(eh),y+int(eh)+8):
   for sx in range(x-4,x+5):
    r,g,b,a=im.getpixel((sx,sy))
    if a>240 and r>g and g>b and r>180:samples.append((r,g,b))
  skin=tuple(sorted(c)[len(c)//2] for c in zip(*samples)) if samples else (247,206,182)
  skin=tuple(round(v*.8+t*.2) for v,t in zip(skin,(246,211,190)))
  result[name]['eyes'].append({'x':x/w,'y':y/h,'width':ew/w,'height':eh/h,'angle':angle,'skin':'#%02x%02x%02x'%skin})
(root/'data/character-presentation.js').write_text('/* Native whole-PNG landmarks. Generated by tools/build_presentation.py. */\nwindow.CHARACTER_PRESENTATION = '+json.dumps(result,indent=2)+';\n')
